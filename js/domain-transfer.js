/* transfer.html on a domain that pages moved to from configured source origins.
   Opened as a popup by js/domain-move.js, it announces itself to its opener,
   accepts payloads only from configured source origins. It also imports a
   downloaded backup file. Items already saved here are kept unless the operator
   chooses to replace them. Requires js/domain-transfer-config.js (generated by
   scripts/stage_domain_sites.mjs) and js/domain-storage.js. */
(function(){
  'use strict';

  var config = window.SBD_DOMAIN_TRANSFER;
  var storage = window.SBD_DOMAIN_STORAGE;
  var status = document.getElementById('transferStatus');
  var panel = document.getElementById('transferResult');
  var fileInput = document.getElementById('backupFile');
  if(!config || !storage || !status || !panel) return;

  var policy = { site: config.site, keys: config.keys, prefixes: config.prefixes, indexedDB: config.indexedDB };
  var sourceOrigins = config.sourceOrigins || [config.sourceOrigin];

  function say(text){ status.textContent = text; }

  function el(tag, className, text){
    var node = document.createElement(tag);
    if(className) node.className = className;
    if(text != null) node.textContent = text;
    return node;
  }

  function plural(count, word){ return count + ' ' + word + (count === 1 ? '' : 's'); }

  function render(result, payload){
    panel.textContent = '';
    panel.hidden = false;
    panel.appendChild(el('h2', '', 'Transfer complete'));
    panel.appendChild(el('p', '', 'Moved ' + plural(result.imported, 'item') + ' to ' + config.domain + '.'
      + (result.kept ? ' ' + plural(result.kept, 'item') + ' already saved here were kept.' : '')));
    if(result.failed.length){
      panel.appendChild(el('p', '', plural(result.failed.length, 'item') + ' could not be saved because browser storage is full: ' + result.failed.join(', ') + '.'));
    }
    if(result.conflicts.length){
      panel.appendChild(el('p', '', 'These items differ from the source copies. The copies here were kept:'));
      var list = el('ul', 'sbd-move-list');
      result.conflicts.forEach(function(key){ list.appendChild(el('li', '', key)); });
      panel.appendChild(list);
      var actions = el('div', 'sbd-move-actions');
      var replace = el('button', 'sbd-move-button', 'Replace them with the source copies');
      replace.type = 'button';
      replace.addEventListener('click', function(){
        if(!window.confirm('Replace ' + plural(result.conflicts.length, 'item') + ' on ' + config.domain + ' with the source copies? The copies here will be overwritten.')) return;
        var replaced = storage.importLocal(policy, payload.localStorage, result.conflicts);
        replace.disabled = true;
        say('Replaced ' + plural(replaced.imported.length, 'item') + ' with the source copies.');
      });
      actions.appendChild(replace);
      panel.appendChild(actions);
    }
    var open = el('a', '', 'Open ' + config.name);
    open.href = config.home;
    var links = el('p', 'sbd-move-links');
    links.appendChild(open);
    panel.appendChild(links);
  }

  function apply(payload){
    return storage.importPayload(policy, payload).then(function(result){
      if(result.failed.length){
        throw new Error(plural(result.failed.length, 'item') + ' could not be saved. Free browser storage and try again; items already copied will be kept.');
      }
      say('Moved ' + plural(result.imported, 'item') + ' to ' + config.domain + '.');
      render(result, payload);
      return result;
    });
  }

  var opener = window.opener;
  if(opener){
    say('Waiting for saved data from the source website.');
    window.addEventListener('message', function(event){
      if(sourceOrigins.indexOf(event.origin) === -1 || event.source !== opener) return;
      var message = event.data || {};
      if(message.type !== 'sbd-domain-transfer-payload' || !message.payload || message.payload.source !== event.origin) return;
      apply(message.payload).then(function(result){
        opener.postMessage({ type: 'sbd-domain-transfer-result', imported: result.imported, kept: result.kept }, event.origin);
        if(!result.conflicts.length && !result.failed.length) setTimeout(function(){ window.close(); }, 2000);
      }, function(error){
        var text = String(error && error.message || error);
        say('The move did not finish: ' + text);
        opener.postMessage({ type: 'sbd-domain-transfer-error', message: text }, event.origin);
      });
    });
    try{
      sourceOrigins.forEach(function(origin){
        opener.postMessage({ type: 'sbd-domain-transfer-ready', site: config.site }, origin);
      });
    }catch(e){
      say('This window lost its connection to the source website. Import a backup file instead.');
    }
  }

  if(fileInput){
    fileInput.addEventListener('change', function(){
      var file = fileInput.files && fileInput.files[0];
      if(!file) return;
      say('Importing ' + file.name + '.');
      file.text().then(function(text){
        return apply(storage.decodeBackup(text));
      }).catch(function(error){
        say('That file could not be imported: ' + String(error && error.message || error));
      });
    });
  }
})();
